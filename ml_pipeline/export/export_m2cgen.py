def write_scoring_constants(out_path: Path, coeffs: dict) -> None:
    """Emit scoring helper constants and functions."""
    feat_order = coeffs["feature_order"]

    content = (
        _dart_file_header("Meta-Learner Scoring Constants")
        + "// Feature order for meta-learner input (19 elements):\n"
        + "// " + ", ".join(feat_order) + "\n\n"
        + "/// Convert a probability to GigCredit score (300-900 scale).\n"
        + "int probabilityToScore(double probability) =>\n"
        + "    (probability * 600 + 300).round().clamp(300, 900);\n"
        + "\n"
        + "/// Grade from score.\n"
        + "String scoreToGrade(int score) {\n"
        + "  if (score >= 800) return 'A+';\n"
        + "  if (score >= 750) return 'A';\n"
        + "  if (score >= 700) return 'B+';\n"
        + "  if (score >= 650) return 'B';\n"
        + "  if (score >= 600) return 'C+';\n"
        + "  if (score >= 550) return 'C';\n"
        + "  return 'D';\n"
        + "}\n"
        + "\n"
        + "/// Risk level from score.\n"
        + "String scoreToRiskLevel(int score) {\n"
        + "  if (score >= 700) return 'Low';\n"
        + "  if (score >= 580) return 'Medium';\n"
        + "  return 'High';\n"
        + "}\n"
    )
    out_path.write_text(content, encoding="utf-8")
    print(f"  ok {out_path.name}")


def main() -> None:
    model_dir  = Path("ml_pipeline/output/models")
    config_dir = Path("ml_pipeline/output/json_configs")
    out_dir    = Path("ml_pipeline/output/dart_exports")
    out_dir.mkdir(parents=True, exist_ok=True)

    print("Exporting pillar models to Dart via m2cgen …")

    for name, fn_name, n_feats in PILLAR_MAP:
        model_path = model_dir / f"{name}.pkl"
        if not model_path.exists():
            print(f"ERROR: {model_path} not found. Run train_pillars.py first.")
            sys.exit(1)
        write_m2cgen_scorer(
            model_path,
            out_dir / f"{name}_scorer.dart",
            fn_name,
            f"P{name[1].upper()} Pillar Scorer ({n_feats} features)",
        )

    print("Exporting Meta-Learner (RandomForestRegressor) to Dart …")
    meta_path = model_dir / "meta_rf.pkl"
    if not meta_path.exists():
        print("ERROR: meta_rf.pkl missing.")
        sys.exit(1)
    
    coeffs_path = config_dir / "meta_coefficients.json"
    if not coeffs_path.exists():
        print("ERROR: meta_coefficients.json missing.")
        sys.exit(1)
    coeffs = json.loads(coeffs_path.read_text(encoding="utf-8"))

    write_m2cgen_meta_scorer(meta_path, out_dir / "meta_scorer.dart", coeffs["feature_order"])

    print("Writing deterministic scorecards …")
    write_scorecard_p5(out_dir / "scorecard_p5.dart")
    write_scorecard_p7(out_dir / "scorecard_p7.dart")

    print("Writing scoring_constants.dart …")
    write_scoring_constants(out_dir / "scoring_constants.dart", coeffs)

    print(f"\nAll Dart exports ready in {out_dir}/")


if __name__ == "__main__":
    main()
